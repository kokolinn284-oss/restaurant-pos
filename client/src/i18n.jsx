const Ctx = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('pos_lang') || 'my');

  useEffect(() => {
    localStorage.setItem('pos_lang', lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key, vars) => {
    if (!key) return '';
    let s = lang === 'en' ? (EN[key] ?? key)
      : lang === 'zh' ? (ZH[key] ?? EN[key] ?? key)
      : (MY[key] ?? key);
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.split(`{${k}}`).join(String(v));
      }
    }
    return s;
  };

  return (
    <Ctx.Provider value={{ lang, setLang, t, isEn: lang === 'en', isZh: lang === 'zh', isMy: lang === 'my' }}>
      {children}
    </Ctx.Provider>
  );
}

export function useI18n() {
  return useContext(Ctx) || { lang: 'my', setLang: () => {}, t: k => k, isEn: false, isZh: false, isMy: true };
}
