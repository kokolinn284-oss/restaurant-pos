const Ctx = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('pos_lang') || 'my');

  useEffect(() => {
    localStorage.setItem('pos_lang', lang);
    document.documentElement.lang = lang === 'en' ? 'en' : 'my';
  }, [lang]);

  const t = (key, vars) => {
    let s = lang === 'en' ? (EN[key] ?? key) : key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };

  return <Ctx.Provider value={{ lang, setLang, t, isEn: lang === 'en' }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  return useContext(Ctx) || { lang: 'my', setLang: () => {}, t: k => k, isEn: false };
}
